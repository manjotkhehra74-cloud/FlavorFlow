(function () {
  'use strict';
  function storeURL(value, platform, packageId) {
    try {
      var url = new URL(value);
      if (url.protocol !== 'https:' || url.username || url.password || url.port) return null;
      if (platform === 'android') {
        if (url.hostname !== 'play.google.com' || url.pathname !== '/store/apps/details' || url.searchParams.get('id') !== packageId) return null;
      } else if (url.hostname !== 'apps.microsoft.com' || !/^\/detail\/[a-zA-Z0-9]+\/?$/.test(url.pathname)) return null;
      return url.href;
    } catch (_) { return null; }
  }
  function configure(config) {
    config = config || {};
    var android = storeURL(config.playStoreUrl, 'android', config.androidPackageId);
    var windows = storeURL(config.windowsStoreUrl, 'windows');
    document.querySelectorAll('[data-play-store]').forEach(function (el) {
      var text = el.querySelector('[data-store-label]');
      if (android) {
        el.href = android;
        el.setAttribute('aria-disabled', 'false');
        el.classList.remove('is-pending');
        if (text) text.textContent = 'Get it on Google Play';
      } else {
        el.removeAttribute('href');
        el.setAttribute('aria-disabled', 'true');
        el.classList.add('is-pending');
        if (text) text.textContent = 'Google Play — coming soon';
      }
    });
    document.querySelectorAll('[data-play-status]').forEach(function (el) {
      el.textContent = android ? 'Open Google Play to install FlavorFlow ERP.' : 'Play Store publication is pending. Installation and QR access will open after approval.';
    });
    document.querySelectorAll('[data-play-qr]').forEach(function (el) {
      el.replaceChildren();
      if (android && typeof window.qrcode === 'function') {
        var qr = window.qrcode(0, 'M');
        qr.addData(android);
        qr.make();
        // SVG is generated by a bundled local library, not a remote QR service.
        el.innerHTML = qr.createSvgTag({cellSize: 4, margin: 16, scalable: true});
        el.setAttribute('data-qr-url', android);
        el.setAttribute('aria-label', 'Scan to open FlavorFlow ERP on Google Play');
      } else {
        el.removeAttribute('data-qr-url');
        el.textContent = 'QR will be available after the Play Store launch';
        el.setAttribute('aria-label', 'Play Store QR code is not yet available');
      }
    });
    document.querySelectorAll('[data-windows-store]').forEach(function (el) {
      var text = el.querySelector('[data-store-label]');
      if (windows) {
        el.href = windows;
        el.setAttribute('aria-disabled', 'false');
        el.classList.remove('is-pending');
        if (text) text.textContent = 'Get it from Microsoft Store';
      } else {
        el.removeAttribute('href');
        el.setAttribute('aria-disabled', 'true');
        el.classList.add('is-pending');
        if (text) text.textContent = 'Download for Windows — coming soon';
      }
    });
  }
  document.addEventListener('click', function (event) {
    var button = event.target.closest('[data-play-store], [data-windows-store]');
    if (button && button.getAttribute('aria-disabled') === 'true') event.preventDefault();
  });
  window.FlavorFlowDistribution = {configure: configure};
  configure(window.FF_DISTRIBUTION);
})();
